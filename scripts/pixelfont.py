# Typographic punctuation LLMs and word processors produce, mapped onto glyphs the font has.
_ALIASES = {'’': "'", '‘': "'", '‚': "'", '′': "'", '‹': "'", '›': "'",
            '“': '"', '”': '"', '„': '"', '″': '"', '«': '"', '»': '"',
            '—': '-', '–': '-', '‐': '-', '‑': '-', '‒': '-', '―': '-', '−': '-',
            '×': 'x', '·': '•', '\t': ' '}
# Letters that Unicode decomposition does not reduce to a plain base letter.
_FOLD = {'ß': 'ss', 'æ': 'ae', 'Æ': 'AE', 'œ': 'oe', 'Œ': 'OE', 'ø': 'o', 'Ø': 'O', 'ł': 'l',
         'Ł': 'L', 'đ': 'd', 'Đ': 'D', 'ð': 'd', 'Ð': 'D', 'þ': 'th', 'Þ': 'Th', 'ı': 'i'}


class PixelFont:
    """Duck-types the bits of a PIL font that gui.py needs."""
    line_height = 11

    def __init__(self, spacing=1, space=3):
        self.spacing = spacing
        self.space = space
        self.glyphs = {}
        for ch, rows in _G.items():
            rows = rows + ['.' * len(rows[0])] * (9 - len(rows))
            w = len(rows[0])
            im = Image.new('1', (w, 9), 0)
            for y, r in enumerate(rows):
                for x, c in enumerate(r):
                    if c == '#':
                        im.putpixel((x, y), 1)
            self.glyphs[ch] = im

    def _norm(self, text):
        """Map text onto the glyph set. Accented letters lose their accent (é -> e) through NFKD
        decomposition, which also turns no-break and thin spaces into plain spaces; anything
        still unknown is left for draw() to show as '?'."""
        out = []
        for c in str(text).replace('…', '...'):
            c = _ALIASES.get(c, c)
            if c == ' ' or c in self.glyphs:
                out.append(c)
            elif c in _FOLD:
                out.append(_FOLD[c])
            else:
                base = ''.join(b for b in unicodedata.normalize('NFKD', c) if not unicodedata.combining(b))
                out.append(base if base and all(b == ' ' or b in self.glyphs for b in base) else c)
        return ''.join(out)

    def getlength(self, text):
        n = 0
        for c in self._norm(text):
            if c == ' ':
                n += self.space + self.spacing
            else:
                n += self.glyphs.get(c, self.glyphs['?']).width + self.spacing
        return max(0, n - self.spacing)

    def draw(self, d, xy, text, fill):
        x, y = xy
        for c in self._norm(text):
            if c == ' ':
                x += self.space + self.spacing
                continue
            g = self.glyphs.get(c, self.glyphs['?'])
            d.bitmap((x, y + 1), g, fill=fill)
            x += g.width + self.spacing

    def render_mask(self, text, scale=1):
        """Text as an 'L' mask image (255 = ink), optionally scaled up with nearest neighbour."""
        w = max(1, self.getlength(text))
        im = Image.new('L', (w, 9), 0)
        from PIL import ImageDraw
        self.draw(ImageDraw.Draw(im), (0, -1), text, 255)
        if scale != 1:
            im = im.resize((w * scale, 9 * scale), Image.NEAREST)
        return im
